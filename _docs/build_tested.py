"""
build_tested.py: writes our own test results onto the site.

    python3 _docs/build_tested.py          (run from anywhere)

From _docs/tested_data.py it writes, idempotently (safe to run again):
  1. on every tested page: a chip under the <h1> that jumps to the results,
     and a "We tested it" section just before the indicator section
     (or before the closing rule box), between <!--tested:start--> markers;
     plus the tested.css link and today's dateModified;
  2. the TESTED map in js/site.js (the hub cards' chips and the filter);
  3. /tested-results.html, the overview of every test.

Famous-strategy pages are generated by _docs/fs_build.py: run this script
again after regenerating them.
"""
import datetime, html, importlib.util, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
spec = importlib.util.spec_from_file_location("tested_data", os.path.join(ROOT, "_docs", "tested_data.py"))
D = importlib.util.module_from_spec(spec); spec.loader.exec_module(D)

CSS_V = 2
CSS_LINK = '<link rel="stylesheet" href="/css/tested.css?v=%d">' % CSS_V
TODAY = datetime.date.today().isoformat()
OVERVIEW = "/tested-results.html"
LABEL = {"edge": "Beat random", "mixed": "Mixed", "none": "No edge", "thin": "Not enough data", "info": "Accuracy check"}


def text(s):
    """HTML fragment -> plain text (for aria labels and JSON)."""
    return html.unescape(re.sub(r"<[^>]+>", "", s))


def chip(p, small=False, href="#tested"):
    return ('<a class="tested-chip%s v-%s" href="%s"><i aria-hidden="true"></i>Tested: <b>%s</b></a>'
            % (" sm" if small else "", p["verdict"], href, p["chip"]))


def section(p):
    o = ['<!--tested:start-->',
         '<section class="tested v-%s" id="tested" aria-labelledby="tested-h">' % p["verdict"],
         '  <div class="tested-top"><span class="tested-label">We tested it</span>'
         '<span class="tested-verdict"><i aria-hidden="true"></i>%s</span></div>' % p["chip"],
         '  <h2 id="tested-h">%s</h2>' % p["headline"],
         '  <p class="tested-lead">%s</p>' % p["lead"]]
    if p.get("stats"):
        o.append('  <ul class="tested-stats">')
        for st in p["stats"]:
            tone = (' class="%s"' % st[2]) if len(st) > 2 else ""
            o.append('    <li><b%s>%s</b><span>%s</span></li>' % (tone, st[0], st[1]))
        o.append('  </ul>')
    t = p.get("table")
    if t:
        o.append('  <div class="tested-table-wrap"><table>')
        o.append('    <thead><tr>' + "".join('<th scope="col">%s</th>' % h for h in t["head"]) + '</tr></thead>')
        o.append('    <tbody>')
        for r in t["rows"]:
            o.append('      <tr>' + "".join("<td>%s</td>" % (c or "&ndash;") for c in r) + '</tr>')
        o.append('    </tbody>')
        o.append('  </table></div>')
    if p.get("notes"):
        o.append('  <ul class="tested-notes">')
        o += ['    <li>%s</li>' % n for n in p["notes"]]
        o.append('  </ul>')
    o.append('  <p class="tested-how"><b>How we tested.</b> %s +1R means a trade won what it risked. Past results don\'t '
             'promise future ones. <a href="%s">Every test result &rsaquo;</a></p>' % (p["how"], OVERVIEW))
    o.append('</section>')
    o.append('<!--tested:end-->')
    return "\n".join("  " + l if l else l for l in o) + "\n\n"


def insert_point(src):
    """Index to insert the section at: the indicator section, else the closing rule box, else the source line."""
    m = re.search(r'class="ind-heading"', src)
    if m:
        a = max(src.rfind('<div class="section-head"', 0, m.start()), src.rfind('<section class="ind-sec"', 0, m.start()))
        if a != -1 and m.start() - a < 400:
            return src.rfind("\n", 0, a) + 1
    for pat in ('<div class="rule">', '<p class="src">', '<footer'):
        i = src.find(pat)
        if i != -1:
            return src.rfind("\n", 0, i) + 1
    raise ValueError("no insert point")


def patch_page(p):
    path = os.path.join(ROOT, p["path"])
    src = open(path, encoding="utf-8").read()
    # clear an earlier run
    src = re.sub(r"[ \t]*<!--tested:start-->.*?<!--tested:end-->\n\n?", "", src, flags=re.S)
    src = re.sub(r"<!--tested-chip-->.*?<!--/tested-chip-->", "", src, flags=re.S)
    # css link, right after apple.css
    src = re.sub(r'<link rel="stylesheet" href="/css/tested\.css\?v=\d+">\n?', "", src)
    src = re.sub(r'(<link rel="stylesheet" href="/css/apple\.css\?v=\d+">\n)', r"\1" + CSS_LINK + "\n", src, count=1)
    if CSS_LINK not in src:
        raise ValueError("apple.css link not found in " + p["path"])
    # chip under the h1
    i = src.find("</h1>")
    src = src[:i + 5] + "<!--tested-chip-->" + chip(p) + "<!--/tested-chip-->" + src[i + 5:]
    # the section
    k = insert_point(src)
    src = src[:k] + section(p) + src[k:]
    src = re.sub(r'"dateModified": "\d{4}-\d{2}-\d{2}"', '"dateModified": "%s"' % TODAY, src, count=1)
    open(path, "w", encoding="utf-8").write(src)


def patch_site_js():
    path = os.path.join(ROOT, "js", "site.js")
    src = open(path, encoding="utf-8").read()
    rows = ",\n".join('    "/%s": ["%s", "%s"]' % (p["path"], p["verdict"], text(p["chip"]).replace('"', '\\"'))
                      for p in D.PAGES)
    block = ("  /* TESTED-START: written by _docs/build_tested.py from _docs/tested_data.py; edit there.\n"
             "     href -> [verdict, chip text]. Feeds the card chips and the Tested filter. */\n"
             "  var TESTED = {\n" + rows + "\n  };\n  /* TESTED-END */\n")
    if "TESTED-START" in src:
        src = re.sub(r"  /\* TESTED-START.*?/\* TESTED-END \*/\n", lambda m: block, src, flags=re.S)
    else:
        raise ValueError("add the TESTED-START/TESTED-END markers to js/site.js first")
    open(path, "w", encoding="utf-8").write(src)


